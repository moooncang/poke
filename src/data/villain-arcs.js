// Villain arcs: a five-stage story with each region's villainous team (45 'regional' storylets).
// Stages: a suspicious sign → first clash → a deepening plot → stopping an operation at the hideout → an ending.
// Progress uses the existing save schema only: stage n sets `villain-<region>-<n>-done` when it succeeds, the
// director records the age a stage was shown in `cooldowns`, and the next stage opens two years after the
// previous one. A failed check or a lost battle leaves the stage open for another try the next year.
// Every stage has a free "stay out of it" option that sets `villain-<region>-closed` and ends the arc.
import { table, check, echoLater, choiceLater } from './event-kit.js';
import { currentRegion } from '../sim/world.js';
import { poke } from '../sim/text.js';

const stageId = (r, n) => `villain-${r}-${n}`;
const done = (r, n) => `villain-${r}-${n}-done`;
const closed = r => `villain-${r}-closed`;

const stageMeta = (r, n) => ({
  once: false, cooldown: 1, weight: () => n > 1 ? 4 : 1,
  when: s => currentRegion(s) === r && !s.flags[done(r, n)] && !s.flags[closed(r)]
    && (n === 1 ? s.party.length > 0 : s.flags[done(r, n - 1)] && s.age - (s.cooldowns[stageId(r, n - 1)] ?? -99) >= 2),
});

/**
 * Builds one region's five stages. `write(go, fight, leave)` returns [title, body, options] for each stage:
 * go(n, more) marks stage n as cleared (put a `check` in `more` to make it a test); fight(n, ...) is a villain
 * battle that clears the stage only on a win; leave(...) is the free option that closes the arc.
 */
function arc(r, write) {
  const go = (n, more = {}) => ({ flag: done(r, n), ...more });
  const fight = (n, opponent, level, win, lose) => ({
    description: n === 5 ? '보스 배틀 · 이기면 이야기의 결말' : '조직 배틀 · 이기면 다음 단계',
    battle: { kind: 'villain', opponent, level }, after: { win: { flag: done(r, n), ...win }, lose },
  });
  const leave = (label, outcome, effects = {}) => [label, 'easygoing', effects, outcome,
    { flag: closed(r), description: '관여하지 않음 · 이 이야기는 여기서 끝난다' }];
  return table('regional', write(go, fight, leave).map(([title, body, options], i) =>
    [stageId(r, i + 1), 12, i ? 80 : 70, title, body, options, stageMeta(r, i + 1)]));
}

