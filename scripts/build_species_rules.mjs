// Builds src/data/species-rules.js from resources/catalog/pokemon.json.
// Non-level triggers (stones, trades, friendship…) are mapped to simplified level gates for the life simulation.
import { readFileSync, writeFileSync } from 'node:fs';

const catalog = JSON.parse(readFileSync(new URL('../resources/catalog/pokemon.json', import.meta.url)));
const ITEM_LEVEL = 30, TRADE_LEVEL = 34, OTHER_LEVEL = 32, FRIENDSHIP_LEVEL = 18;

const table = {};
for (const species of catalog) {
  const from = species.evolves_from_species_id;
  if (!from || species.id > 1025) continue;
  const rules = species.evolution_rules_raw || [];
  const levelled = rules.find(r => r.minimum_level);
  const friendship = rules.find(r => r.minimum_happiness || r.minimum_affection);
  const trigger = rules[0]?.evolution_trigger_id;
  const rule = levelled ? [species.id, Number(levelled.minimum_level)]
    : friendship ? [species.id, FRIENDSHIP_LEVEL, 1]
    : trigger === '3' ? [species.id, ITEM_LEVEL]
    : trigger === '2' ? [species.id, TRADE_LEVEL]
    : [species.id, OTHER_LEVEL];
  (table[from] ||= []).push(rule);
}

const legendary = catalog.filter(p => p.id <= 1025 && (p.is_legendary || p.is_mythical)).map(p => p.id);
const body = Object.entries(table).map(([from, rules]) => `${from}:${JSON.stringify(rules)}`).join(',');
writeFileSync(new URL('../src/data/species-rules.js', import.meta.url),
  `// Generated by scripts/build_evolutions.mjs from PokéAPI data.\n// EVOLUTIONS: species → [targetId, level, needsAffection?]\nexport const EVOLUTIONS = {${body}};\nexport const LEGENDARY = new Set(${JSON.stringify(legendary)});\n`);
console.log(`evolution sources: ${Object.keys(table).length}`);
